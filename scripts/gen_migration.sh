#!/usr/bin/env bash
# Render Alembic revisions to SQL files that the Supabase CLI applies.
#   scripts/gen_migration.sh <from_rev|base> <to_rev> <timestamp> <slug>
# Example: scripts/gen_migration.sh base 0001 20261127000100 foundation
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
FROM="$1"; TO="$2"; TS="$3"; SLUG="$4"
OUT="$ROOT/supabase/migrations/${TS}_${SLUG}.sql"
RANGE="$TO"; [ "$FROM" != "base" ] && RANGE="$FROM:$TO"
{
  echo "-- GENERATED by scripts/gen_migration.sh from Alembic revision(s) $FROM -> $TO."
  echo "-- Do not edit by hand: change backend models / db/sql and regenerate."
  echo "create schema if not exists cornucopia;"
  (cd "$ROOT/backend" && uv run --quiet alembic -c ../db/alembic.ini upgrade "$RANGE" --sql)
} > "$OUT"
echo "wrote $OUT"
